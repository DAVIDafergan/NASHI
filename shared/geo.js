const toRad = (d) => (d * Math.PI) / 180;
const km = (a, b) => {
  const dLat = toRad(b[0] - a[0]), dLng = toRad(b[1] - a[1]);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
};

/** Nearest listed city to a position, or null when the position is far from all of them (outside Israel). */
export function nearestCity(lat, lng, maxKm = 40) {
  let best = null, bestKm = Infinity;
  for (const [city, c] of Object.entries(CITY_COORDS)) {
    const d = km([lat, lng], c);
    if (d < bestKm) { best = city; bestKm = d; }
  }
  return bestKm <= maxKm ? { city: best, km: Math.round(bestKm) } : null;
}
