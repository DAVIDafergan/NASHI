// Service agreement every NGO signs before opening a campaign. Rendered as HTML (printable → PDF from the browser).
const VERSION = '1.0';
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const OPERATOR = { name: process.env.OPERATOR_NAME || 'GiveIL', number: process.env.OPERATOR_NUMBER || '213603400', address: process.env.OPERATOR_ADDRESS || '', email: 'hello@giveil.com' };

function clauses(p) {
  return `
<h2>הסכם שימוש בפלטפורמת GiveIL לגיוס תרומות</h2>
<p class="meta">גרסה ${VERSION} · נערך ונחתם ביום ${esc(p.date)}</p>
<p><b>בין:</b> ${esc(OPERATOR.name)}, עסק מורשה מס' ${esc(OPERATOR.number)}${OPERATOR.address ? ', ' + esc(OPERATOR.address) : ''} (להלן: "המפעילה")</p>
<p><b>לבין:</b> ${esc(p.org)}, ${p.orgNumber ? 'מס' + "'" + ' תאגיד/עמותה ' + esc(p.orgNumber) + ', ' : ''}באמצעות ${esc(p.name)}, ת.ז. ${esc(p.idNumber)}, בתפקיד ${esc(p.roleTitle || 'מורשה חתימה')} (להלן: "העמותה")</p>
<p><b>הואיל</b> והמפעילה מפעילה פלטפורמה מקוונת בכתובת giveil.com המאפשרת לעמותות להקים דפי קמפיין לגיוס תרומות (להלן: "הפלטפורמה"); <b>והואיל</b> והעמותה מעוניינת לעשות שימוש בפלטפורמה; לפיכך הוסכם והותנה בין הצדדים כדלקמן:</p>

<h3>1. מהות השירות</h3>
<p>1.1. המפעילה מעמידה לרשות העמותה כלים טכנולוגיים: דפי קמפיין, כפתורי תרומה, דפי שגרירים, מסך אירוע, שליחת הודעות, דשבורד ניהול ועוזר דיגיטלי.</p>
<p>1.2. <b>המפעילה אינה גובה, מחזיקה או מעבירה כספי תרומות.</b> כספי התרומות עוברים ישירות מהתורם לחשבון העמותה אצל ספק הסליקה שבחרה העמותה, על פי הסכם ישיר בין העמותה לספק. המפעילה אינה צד לעסקת התרומה.</p>
<p>1.3. הפלטפורמה ניתנת כמות שהיא (AS IS). המפעילה תפעל באופן סביר לזמינות השירות אך אינה מתחייבת לרציפות או להיעדר תקלות.</p>

<h3>2. הצהרות והתחייבויות העמותה</h3>
<p>2.1. העמותה מצהירה כי היא תאגיד הרשום כדין, פעיל ובעל ניהול תקין, וכי החותם מוסמך להתקשר בהסכם זה בשמה.</p>
<p>2.2. העמותה אחראית באופן בלעדי לתוכן הקמפיינים, לחוקיות מטרותיהם, לשימוש בכספים למטרה שפורסמה, להנפקת קבלות לתורמים (לרבות קבלות לפי סעיף 46 לפקודת מס הכנסה), לדיווחים לרשויות ולעמידה בכל דין, לרבות חוק העמותות, חוק הגנת הפרטיות, חוק איסור הלבנת הון וחוק התקשורת (דיוור).</p>
<p>2.3. העמותה תאשר תרומות ידנית (ביט, פייבוקס, דף תשלום חיצוני) רק לאחר שווידאה שהכסף התקבל בפועל, ותטפל בפניות תורמים, החזרים והוראות קבע מול ספק הסליקה.</p>
<p>2.4. העמותה לא תעלה תוכן מפר זכויות, מטעה, פוגעני או בלתי חוקי, ותשיג את כל ההסכמות הנדרשות לפרסום תמונות ושמות.</p>
<p>2.5. העמותה תשמור על סודיות פרטי ההתחברות ותישא באחריות לכל פעולה בחשבונה.</p>

<h3>3. תמורה</h3>
<p>3.1. השימוש בפלטפורמה כפוף לתוכנית המחירים המפורסמת באתר במועד פתיחת הקמפיין. המפעילה אינה גובה אחוזים מכספי התרומות. עמלות ספק הסליקה חלות על העמותה בלבד.</p>
<p>3.2. דמי שירות ששולמו אינם מוחזרים, למעט אם נקבע אחרת בכתב.</p>

<h3>4. מידע ופרטיות</h3>
<p>4.1. פרטי התורמים והשגרירים שנאספים בדפי הקמפיין של העמותה הם בבעלות העמותה; המפעילה מעבדת אותם עבורה בהתאם למדיניות הפרטיות של הפלטפורמה ולחוק הגנת הפרטיות, התשמ"א-1981 ותקנותיו.</p>
<p>4.2. העמותה מתחייבת לעשות במידע שימוש כדין בלבד, לא להעבירו לצדדים שלישיים ללא הסכמה, ולאפשר לתורמים לממש את זכויותיהם.</p>
<p>4.3. המפעילה רשאית להציג את הקמפיין ואת לוגו העמותה בדף "גלו קמפיינים" ובחומרי שיווק של הפלטפורמה, אלא אם העמותה ביקשה אחרת בכתב.</p>

<h3>5. הגבלת אחריות ושיפוי</h3>
<p>5.1. המפעילה לא תישא באחריות לכל נזק ישיר או עקיף, לרבות אובדן תרומות, אובדן הכנסה או פגיעה במוניטין, הנובע מהשימוש בפלטפורמה, מתקלות, מפעולות ספקי סליקה או צדדים שלישיים, או מכוח עליון. בכל מקרה אחריות המפעילה לא תעלה על דמי השירות ששילמה העמותה ב-12 החודשים שקדמו לאירוע.</p>
<p>5.2. העמותה תשפה את המפעילה בגין כל תביעה, דרישה, נזק או הוצאה (לרבות שכר טרחת עו"ד) שייגרמו עקב הפרת הסכם זה, הפרת דין, תוכן שהעלתה או מחלוקת עם תורמים או ספקים.</p>

<h3>6. תקופה וסיום</h3>
<p>6.1. ההסכם בתוקף מיום חתימתו וכל עוד לעמותה חשבון בפלטפורמה.</p>
<p>6.2. המפעילה רשאית להשעות או לסגור קמפיין או חשבון בהפרה או בחשד להפרת דין, ללא הודעה מוקדמת. העמותה רשאית לסגור את חשבונה בכל עת.</p>
<p>6.3. סעיפים 2, 4 ו-5 ימשיכו לחול גם לאחר סיום ההסכם.</p>

<h3>7. כללי</h3>
<p>7.1. הסכם זה, יחד עם תנאי השימוש ומדיניות הפרטיות המפורסמים באתר, ממצה את ההסכמות בין הצדדים. שינוי יחייב בכתב.</p>
<p>7.2. על הסכם זה יחולו דיני מדינת ישראל, וסמכות השיפוט הבלעדית נתונה לבתי המשפט במחוז ירושלים.</p>
<p>7.3. חתימה אלקטרונית על הסכם זה מהווה חתימה מחייבת לכל דבר ועניין בהתאם לחוק חתימה אלקטרונית, התשס"א-2001.</p>
`;
}

